// Helper to convert inputs into fully typed Product models with raw ingredients string
export function buildProductModels(): Product[] {
  const allInputs = [...SEED_PRODUCTS_DATA, ...ADDITIONAL_SEEDS];

  return allInputs.map((item, index) => {
    const rawList = item.ingredients.map((i) => i.name).join(', ');
    const productIngredients: ProductIngredient[] = item.ingredients.map((ing, iIdx) => {
      const ingredientId = `ing-${ing.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`;
      const ingredientModel: Ingredient = {
        id: ingredientId,
        name: ing.name,
        inciName: ing.inciName,
        category: ing.category,
        description: ing.description,
      };

      return {
        id: `pi-${index}-${iIdx}`,
        productId: `prod-${item.slug}`,
        ingredientId,
        rankOrder: iIdx + 1,
        isActiveIngredient: ing.isActive,
        ingredient: ingredientModel,
      };
    });

    return {
      id: `prod-${item.slug}`,
      slug: item.slug,
      brand: item.brand,
      name: item.name,
      price: item.price,
      currency: 'USD',
      imageUrl: item.imageUrl,
      affiliateUrl: item.affiliateUrl,
      isLuxuryTarget: item.isLuxuryTarget,
      ingredientsRaw: rawList,
      ingredients: productIngredients,
      clicksCount: Math.floor(Math.random() * 450) + 120,
    };
  });
}

